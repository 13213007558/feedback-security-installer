"""Optional policies for reviewing wheel launch entries before installation.

A "launch entry" is anything a wheel installs that can cause Python code to
run outside of an explicit ``import`` of the package, or that modifies
:data:`sys.path` at interpreter start-up. This module distinguishes four
categories:

``pth_path``
    A non-comment, non-blank line in a ``.pth`` file that the target
    interpreter's :mod:`site` machinery treats as a directory to add to
    :data:`sys.path`.

``pth_import``
    A line in a ``.pth`` file starting with ``import `` or ``import\t``.
    :func:`site.addpackage` executes these lines with :func:`exec` while the
    interpreter is starting.

``script``
    An executable file shipped inside the wheel's ``.data/scripts`` (or, for
    files already at the wheel root, the ``scripts`` scheme) directory.

``entry_point``
    A launcher generated from ``entry_points.txt`` ``console_scripts`` /
    ``gui_scripts`` sections.

Classification follows the actual semantics of the running interpreter's
:mod:`site` module -- line by line, for the files that :func:`site.addpackage`
would actually enumerate -- rather than searching arbitrary file contents for
the word ``import``.

The check only covers launch entries. Passing this policy does not prove that
the package's ordinary code is safe.
"""

import enum
import json
import posixpath
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, cast

from installer.exceptions import InstallerError

if TYPE_CHECKING:
    from os import PathLike

__all__ = [
    "EntryCategory",
    "LaunchEntry",
    "LaunchEntryPolicy",
    "PolicyAction",
    "PolicyRule",
    "PolicyViolation",
    "classify_pth_line",
    "is_pth_launch_file",
    "load_launch_entry_policy",
    "policy_from_dict",
]

# Return values of :func:`classify_pth_line`, mirroring ``site.addpackage``.
PTH_COMMENT = "comment"
PTH_BLANK = "blank"
PTH_IMPORT = "import"
PTH_PATH = "path"


class EntryCategory(enum.Enum):
    """The kind of launch entry a wheel provides."""

    PTH_PATH = "pth_path"
    PTH_IMPORT = "pth_import"
    SCRIPT = "script"
    ENTRY_POINT = "entry_point"


class PolicyAction(enum.Enum):
    """What a policy does with a matching launch entry."""

    ALLOW = "allow"
    DENY = "deny"


@dataclass(frozen=True)
class LaunchEntry:
    """A single launch entry that a policy decision is made for.

    :param category: how the target interpreter treats this entry
    :param archive: where the entry came from (wheel file name or
        ``distribution-version`` label)
    :param source_path: path of the entry inside the wheel archive, or the
        additional-metadata key when the entry is generated by the caller
    :param scheme: installation scheme the entry is written to
    :param destination_path: final path within ``scheme`` after ``.data``
        relocation
    :param name: name the policy matches against (script or file base name)
    :param module: ``module:attr`` target of an entry point, otherwise
        :data:`None`
    :param line_numbers: 1-based line numbers inside a ``.pth`` file that
        contribute to this entry; empty for non-``.pth`` entries
    """

    category: EntryCategory
    archive: str
    source_path: str
    scheme: str
    destination_path: str
    name: str
    module: str | None = None
    line_numbers: tuple[int, ...] = ()


@dataclass(frozen=True)
class PolicyRule:
    """A single policy rule.

    An entry matches a rule when every non-empty selector applies. Empty
    selectors match every entry. The first matching rule in policy order
    decides the entry; if no rule matches, the policy's default action does.

    :param action: allow or deny matching entries
    :param categories: entry categories this rule applies to (empty = all)
    :param names: matched case-insensitively against :attr:`LaunchEntry.name`
        (empty = any name)
    :param modules: matched exactly against :attr:`LaunchEntry.module`; a rule
        using this selector never matches entries without a module target
        (empty = any module)
    """

    action: PolicyAction
    categories: tuple[EntryCategory, ...] = ()
    names: tuple[str, ...] = ()
    modules: tuple[str, ...] = ()

    def matches(self, entry: LaunchEntry) -> bool:
        """Whether ``entry`` is selected by this rule."""
        if self.categories and entry.category not in self.categories:
            return False
        if self.names and entry.name.casefold() not in {
            name.casefold() for name in self.names
        }:
            return False
        if self.modules and (entry.module is None or entry.module not in self.modules):
            return False
        return True


@dataclass(frozen=True)
class LaunchEntryPolicy:
    """An ordered collection of rules for launch entries.

    :param default_action: action for entries that no rule matches
    :param rules: ordered rules; the first match wins
    """

    default_action: PolicyAction
    rules: tuple[PolicyRule, ...] = ()

    def decide(self, entry: LaunchEntry) -> tuple[PolicyAction, str]:
        """Return the action and a human-readable reason for ``entry``."""
        for index, rule in enumerate(self.rules):
            if rule.matches(entry):
                return rule.action, f"matched rule {index + 1}"
        return self.default_action, "matched no rule (default action)"

    def evaluate(self, entries: Sequence[LaunchEntry]) -> None:
        """Decide on every entry, raising before anything is written.

        :raises PolicyViolation: if one or more entries are denied, including
            entries whose final destinations collide after case folding.
        """
        violations: list[tuple[LaunchEntry, str]] = []

        seen_destinations: dict[tuple[str, str], LaunchEntry] = {}
        for entry in entries:
            key = (entry.scheme, entry.destination_path.casefold())
            previous = seen_destinations.get(key)
            if previous is not None:
                violations.append(
                    (
                        entry,
                        "duplicate final destination "
                        f"{entry.scheme}:{entry.destination_path} "
                        f"(also provided by {previous.source_path})",
                    )
                )
                continue
            seen_destinations[key] = entry

            action, reason = self.decide(entry)
            if action is PolicyAction.DENY:
                violations.append((entry, reason))

        if violations:
            raise PolicyViolation(violations)


class PolicyViolation(InstallerError):
    """Raised when a launch entry policy rejects one or more entries.

    The message reports where each entry came from and where it would have
    been written. File contents -- which may contain secrets -- are never
    included.
    """

    def __init__(self, violations: Sequence[tuple[LaunchEntry, str]]) -> None:
        self.violations = violations
        lines = [
            f"Launch entry policy denied {len(violations)} launch "
            f"{'entry' if len(violations) == 1 else 'entries'}:"
        ]
        for entry, reason in violations:
            lines.append(
                f"- {entry.category.value} from {entry.archive} "
                f"({entry.source_path}) -> {entry.scheme}:"
                f"{entry.destination_path}: {reason}"
            )
        super().__init__("\n".join(lines))


def classify_pth_line(line: str) -> str:
    """Classify one line of a ``.pth`` file, as :func:`site.addpackage` would.

    :param line: a single line, without its line ending
    :return: one of :data:`PTH_COMMENT`, :data:`PTH_BLANK`,
        :data:`PTH_IMPORT` or :data:`PTH_PATH`.

    Only :data:`PTH_IMPORT` and :data:`PTH_PATH` produce launch entries;
    comments and blank lines are ignored by :mod:`site`, exactly as here.
    """
    if line.startswith("#"):
        return PTH_COMMENT
    if line.strip() == "":
        return PTH_BLANK
    if line.startswith(("import ", "import\t")):
        return PTH_IMPORT
    return PTH_PATH


def is_pth_launch_file(destination_path: str) -> bool:
    """Whether ``destination_path`` is a ``.pth`` file :mod:`site` would read.

    :mod:`site` only enumerates the top level of a site directory, ignores
    dot-files, and looks for the ``.pth`` suffix. The suffix comparison here
    is case-insensitive so a wheel cannot smuggle an un-reviewed entry using
    an upper-case suffix on a case-insensitive file system.

    :param destination_path: final path within an installation scheme
    """
    basename = posixpath.basename(destination_path)
    return (
        posixpath.dirname(destination_path) == ""
        and not basename.startswith(".")
        and basename.casefold().endswith(".pth")
    )


def _enum_value(enum_type: type[enum.Enum], value: object, field_name: str) -> enum.Enum:
    if not isinstance(value, str):
        msg = f"{field_name} must be a string, got {type(value).__name__}"
        raise ValueError(msg)
    try:
        return enum_type(value)
    except ValueError:
        allowed = ", ".join(member.value for member in enum_type)
        msg = f"invalid {field_name} {value!r}; expected one of: {allowed}"
        raise ValueError(msg) from None


def _string_tuple(value: object, field_name: str) -> tuple[str, ...]:
    if isinstance(value, (str, bytes, Mapping)) or not isinstance(value, Iterable):
        msg = f"{field_name} must be a list of strings"
        raise ValueError(msg)
    items = tuple(value)
    if not all(isinstance(item, str) for item in items):
        msg = f"{field_name} must contain only strings"
        raise ValueError(msg)
    return items


def policy_from_dict(data: object) -> LaunchEntryPolicy:
    """Build a :class:`LaunchEntryPolicy` from a JSON-like mapping.

    Expected shape::

        {
            "default_action": "deny",
            "rules": [
                {
                    "action": "allow",
                    "categories": ["entry_point"],
                    "names": ["my-command"],
                    "modules": ["mypkg.cli:main"]
                }
            ]
        }

    Every rule field except ``action`` is optional. Rules are evaluated in
    order and the first match wins.

    :raises ValueError: if the mapping does not describe a valid policy.
    """
    if not isinstance(data, Mapping):
        msg = "policy configuration must be a JSON object"
        raise ValueError(msg)

    default_action = cast(
        "PolicyAction",
        _enum_value(PolicyAction, data.get("default_action"), "default_action"),
    )

    raw_rules = data.get("rules", ())
    if isinstance(raw_rules, (str, bytes, Mapping)) or not isinstance(
        raw_rules, Iterable
    ):
        msg = "rules must be a list of rule objects"
        raise ValueError(msg)

    rules: list[PolicyRule] = []
    for raw_rule in raw_rules:
        if not isinstance(raw_rule, Mapping):
            msg = "each rule must be a JSON object"
            raise ValueError(msg)
        action = cast(
            "PolicyAction", _enum_value(PolicyAction, raw_rule.get("action"), "action")
        )
        raw_categories = raw_rule.get("categories", ())
        categories = tuple(
            cast("EntryCategory", _enum_value(EntryCategory, item, "categories"))
            for item in _string_tuple(raw_categories, "categories")
        )
        rules.append(
            PolicyRule(
                action=action,
                categories=categories,
                names=_string_tuple(raw_rule.get("names", ()), "names"),
                modules=_string_tuple(raw_rule.get("modules", ()), "modules"),
            )
        )

    return LaunchEntryPolicy(default_action=default_action, rules=tuple(rules))


def load_launch_entry_policy(path: "str | PathLike[str]") -> LaunchEntryPolicy:
    """Load a :class:`LaunchEntryPolicy` from a JSON file.

    :param path: file system path of the JSON configuration
    :raises ValueError: if the file does not contain a valid policy.
    """
    with Path(path).open(encoding="utf-8") as stream:
        data = json.load(stream)
    return policy_from_dict(data)
